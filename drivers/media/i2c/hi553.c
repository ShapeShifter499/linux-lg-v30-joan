/*
 * Hynix HI553 5MP image sensor driver
 *
 * The front (VT) camera of the LG V30 (joan): a fixed-focus 5 MP sensor,
 * wired by LG to BLSP2 I2C2 (downstream "i2c_8"), CSIPHY2 and MCLK2, with
 * the BRCF016GWZ module EEPROM on the same bus.
 *
 * The register settings are LG's, recovered from the camera sensor library
 * (libmmcamera_hi553.so) of the stock US998 30b firmware and byte-identical
 * in the LineageOS SGCMarkus vendor trees: three 8-bit loads into the
 * sensor's 0x2000 SRAM block, a common PLL/ISP block, and per-mode output
 * registers for 2560x1920, 2560x1440 and 1280x720 (the mode list LG applies
 * after its init; only the registers that differ from the 2560x1920 list
 * are carried in the two smaller modes).  All modes share line length 2816
 * and frame length 2083 at a 220 MHz CSI-2 link (4 lanes, RAW10, 30 fps):
 * LG's camera_config.xml gives the front camera LaneMask 0x1F (four data
 * lanes plus clock), and the library's op_pixel_clk of 176 MHz over four
 * RAW10 lanes is 440 Mb/s per lane.
 *
 * The part follows the HI556/HI846 register map: 16-bit register data,
 * chip ID 0x0553 readable at 0x0f16, streaming controlled by 0x0a00.  The
 * exposure, gain and frame-length registers are LG's: the sensor library's
 * output descriptor (libmmcamera_hi553.so @0x8fd0) lists x/y output
 * 0x0a12/0x0a14, line length 0x0008, frame length 0x0006, coarse exposure
 * 0x0004 and analogue gain 0x003a, and its exposure fill writes exactly
 * those, plus 1.0x (0x0100) digital gain to 0x0126/0x012a/0x012c.
 */

